import { access, constants, mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"
import type { EnvName } from "@sixb/core/env"
import { SixbCliError } from "./errors"

const GENERATED_MARK = "# Generated by sixb env pull"
const READ_TIMEOUT_MS = 10_000

/**
 * What Bun reads from a `.env` file, by asking Bun: a second parser would disagree with the one the
 * app runs on. The child has an empty environment and an empty directory, so the result holds this
 * file's values and nothing else. A `$NAME` in the file sees only that file.
 */
export async function readEnvFile(path: string): Promise<Record<string, string>> {
  // Bun reads a file it can't open as an empty one, which would read as having nothing to lose.
  await access(path, constants.R_OK).catch(() => {
    throw new SixbCliError(`[SixbEnv] Could not read ${path}.`)
  })

  const directory = await mkdtemp(join(tmpdir(), "sixb-env-read-"))
  try {
    const child = Bun.spawn(
      [
        process.execPath,
        `--env-file=${resolve(path)}`,
        "-e",
        "process.stdout.write(JSON.stringify(process.env))",
      ],
      {
        cwd: directory,
        env: {},
        stdin: "ignore",
        stdout: "pipe",
        stderr: "ignore",
        timeout: READ_TIMEOUT_MS,
      }
    )
    const [output, code] = await Promise.all([new Response(child.stdout).text(), child.exited])
    // Never quote the output: it holds the file's values.
    if (code !== 0) throw new SixbCliError(`[SixbEnv] Could not read ${path}.`)
    return JSON.parse(output) as Record<string, string>
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
}

/** Whether this `.env` came from `sixb env pull`, so overwriting it loses nothing. */
export async function isGeneratedEnvFile(path: string): Promise<boolean> {
  const text = await readFile(path, "utf8").catch(() => "")
  return text.startsWith(GENERATED_MARK)
}

/**
 * Writes `.env` readable only by its owner, or not at all. The new file is read back through Bun
 * before it replaces the old one, because Bun's `.env` format can't hold every value: a trailing
 * backslash swallows the closing quote and the next line, and a carriage return becomes a newline.
 */
export async function writeEnvFile(
  path: string,
  values: Readonly<Record<string, string>>,
  env: EnvName
): Promise<void> {
  // One fixed name, so a pull that was killed leaves no copy of the values behind for long.
  const temporary = `${path}.pull.tmp`
  try {
    await rm(temporary, { force: true })
    await writeFile(temporary, renderEnvFile(values, env), { mode: 0o600, flag: "wx" })

    const written = await readEnvFile(temporary)
    const names = new Set([...Object.keys(values), ...Object.keys(written)])
    const unreadable = [...names].filter((name) => written[name] !== values[name]).sort()
    if (unreadable.length > 0) {
      throw new SixbCliError(
        `[SixbEnv] A .env file can't hold the value of ${unreadable.join(", ")}.`,
        {
          remediation:
            "Change the value so it has no carriage return and doesn't end in a backslash, and doesn't use all of ' \" and `.",
        }
      )
    }

    await rename(temporary, path)
  } finally {
    await rm(temporary, { force: true })
  }
}

function renderEnvFile(values: Readonly<Record<string, string>>, env: EnvName): string {
  const lines = Object.entries(values)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, value]) => `${name}=${quoted(value)}`)
  const header = `${GENERATED_MARK} (${env}). Edits are overwritten: use .env.local for your own.`
  return `${[header, ...lines].join("\n")}\n`
}

/**
 * Bun expands `$` in every quote style, so it's always escaped. Single quotes and backticks keep
 * everything else as written; double quotes also turn `\n` into a newline, so they come last.
 */
function quoted(value: string): string {
  const quote = ["'", "`", '"'].find((candidate) => !value.includes(candidate)) ?? "'"
  return `${quote}${value.replaceAll("$", "\\$")}${quote}`
}
