/** What the fake source holds, kept in a file because the CLI loads the source from sixb.env.ts. */
interface SourceState {
  dev?: Record<string, string>
  prod?: Record<string, string>
  /** Makes reads fail: `down` is an outage, `refused` is a refusal. */
  fail?: "down" | "refused"
  /** Environments this person can't read. */
  noAccess?: string[]
  lastToken?: string
}

const FAKE_SOURCE = `
  import { EnvSourceUnreachableError } from "@sixb/core/env"

  const file = new URL("./source.json", import.meta.url).pathname
  const load = async () => JSON.parse(await Bun.file(file).text())
  const save = (state) => Bun.write(file, JSON.stringify(state))
  const assertReadable = (state, env) => {
    if (state.fail === "down") throw new EnvSourceUnreachableError("[Fake] down")
    if (state.fail === "refused") throw new Error("[Fake] refused")
    if (state.noAccess?.includes(env)) throw new Error("[Fake] no access")
  }

  export const source = {
    async names(env) {
      const state = await load()
      assertReadable(state, env)
      return Object.keys(state[env] ?? {})
    },
    async read(env, options) {
      const state = await load()
      assertReadable(state, env)
      await save({ ...state, lastToken: options?.token })
      return state[env] ?? {}
    },
    async write(env, values) {
      const state = await load()
      await save({ ...state, [env]: { ...state[env], ...values } })
    },
  }
`

async function project(state: SourceState, vars: Record<string, string>): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), "sixb-env-"))
  projects.push(dir)
  await mkdir(join(dir, "node_modules/@sixb"), { recursive: true })
  await symlink(CORE_PACKAGE, join(dir, "node_modules/@sixb/core"))
  await writeFile(join(dir, "source.json"), JSON.stringify(state))
  await writeFile(join(dir, "fake-source.ts"), FAKE_SOURCE)
  await writeFile(
    join(dir, "sixb.env.ts"),
    `import { source } from "./fake-source"\nexport default { source, vars: ${JSON.stringify(vars)} }\n`
  )
  return dir
}

const sourceState = async (dir: string): Promise<SourceState> =>
  JSON.parse(await readFile(join(dir, "source.json"), "utf8"))

const dotEnv = (dir: string) => readFile(join(dir, ".env"), "utf8")

const GENERATED_ENV = "# Generated by sixb env pull (prod).\nA='current'\n"

describe("sixb env pull", () => {
  test("writes dev by default, readable only by its owner", async () => {
    const dir = await project({ dev: { A: "dev-value" } }, { A: "required" })

    const result = await runInProcess(() => runEnvPull({ cwd: dir }))

    expect(result.error).toBeUndefined()
    expect(result.output).toContain("Wrote 1 variable to .env")
    expect(await dotEnv(dir)).toContain("A='dev-value'")
    expect((await stat(join(dir, ".env"))).mode & 0o777).toBe(0o600)
  })

  test("never prints a value", async () => {
    const dir = await project({ dev: { A: "the-secret-value" } }, { A: "required" })

    const result = await runInProcess(() => runEnvPull({ cwd: dir }))

    expect(result.output + result.stderr).not.toContain("the-secret-value")
  })

  test("stops when a required name isn't in the source, leaving .env alone", async () => {
    const dir = await project({ dev: { A: "1" } }, { A: "required", MISSING: "required" })
    await writeFile(join(dir, ".env"), GENERATED_ENV)

    const error = await runEnvPull({ cwd: dir }).catch((failure) => failure)

    expect(String(error)).toContain("dev is missing MISSING")
    expect(errorRemediation(error)).toContain("sixb env set MISSING --env dev")
    expect(await dotEnv(dir)).toBe(GENERATED_ENV)
  })

  test("overwrites a generated .env, dropping a name the source no longer has", async () => {
    const dir = await project({ dev: { B: "2" } }, {})
    await writeFile(join(dir, ".env"), GENERATED_ENV)

    await runInProcess(() => runEnvPull({ cwd: dir }))

    expect(await dotEnv(dir)).not.toContain("A=")
    expect(await dotEnv(dir)).toContain("B='2'")
  })

  // Reproduce: remove the refuseToLoseValues call in commands/env.ts.
  test("stops rather than lose a hand-written value, naming only the variable", async () => {
    const dir = await project({ dev: { A: "from-source" } }, {})
    const handWritten = "A=mine-only\nB=also-mine\n"
    await writeFile(join(dir, ".env"), handWritten)

    const error = await runEnvPull({ cwd: dir }).catch((failure) => failure)

    expect(String(error)).toContain("written by hand")
    expect(String(error)).toContain("A, B")
    expect(String(error)).not.toContain("mine-only")
    expect(await dotEnv(dir)).toBe(handWritten)
  })

  test("--force replaces a hand-written .env", async () => {
    const dir = await project({ dev: { A: "from-source" } }, {})
    await writeFile(join(dir, ".env"), "A=mine-only\n")

    await runInProcess(() => runEnvPull({ cwd: dir, force: true }))

    expect(await dotEnv(dir)).toContain("A='from-source'")
  })

  test("takes over a hand-written .env the source already matches", async () => {
    const dir = await project({ dev: { A: "same" } }, {})
    await writeFile(join(dir, ".env"), "A=same\n")

    await runInProcess(() => runEnvPull({ cwd: dir }))

    expect(await dotEnv(dir)).toContain("Generated by sixb env pull")
  })

  // Reproduce: remove the prod check at the top of runEnvPull.
  test("refuses prod without a server's token file", async () => {
    const dir = await project({ prod: { A: "prod-value" } }, {})

    const error = await runEnvPull({ cwd: dir, env: "prod" }).catch((failure) => failure)

    expect(String(error)).toContain("stay on servers")
    expect(await Bun.file(join(dir, ".env")).exists()).toBe(false)
  })

  test("a server pulls prod with the token in its file", async () => {
    const dir = await project({ prod: { A: "prod-value" } }, {})
    const tokenFile = join(dir, "env-token")
    await writeFile(tokenFile, "server-token\n")

    await runInProcess(() => runEnvPull({ cwd: dir, env: "prod", tokenFile }))

    expect((await sourceState(dir)).lastToken).toBe("server-token")
    expect(await dotEnv(dir)).toContain("A='prod-value'")
  })

  test.each([
    ["missing", null, "Could not read the token file"],
    ["empty", "  \n", "is empty"],
  ])("fails on a %s token file", async (_case, contents, message) => {
    const dir = await project({ prod: {} }, {})
    const tokenFile = join(dir, "env-token")
    if (contents !== null) await writeFile(tokenFile, contents)

    const error = await runEnvPull({ cwd: dir, env: "prod", tokenFile }).catch((f) => f)

    expect(String(error)).toContain(message)
  })

  // Reproduce: remove the check in runEnvPull. Rolling back to a commit whose sixb.env.ts declares
  // only names then stops at the pull, with the code already applied.
  test("a server deploying a commit with no source keeps its .env", async () => {
    const dir = await project({}, {})
    await writeFile(join(dir, "sixb.env.ts"), "export default { vars: {} }\n")
    await writeFile(join(dir, ".env"), "A=mine\n")
    const tokenFile = join(dir, "env-token")
    await writeFile(tokenFile, "server-token")

    const result = await runInProcess(() => runEnvPull({ cwd: dir, env: "prod", tokenFile }))

    expect(result.error).toBeUndefined()
    expect(result.output).toContain("Kept the current .env")
    expect(await dotEnv(dir)).toBe("A=mine\n")
  })

  test("on a laptop, a project with no source says so", async () => {
    const dir = await project({}, {})
    await writeFile(join(dir, "sixb.env.ts"), "export default { vars: {} }\n")

    expect(String(await runEnvPull({ cwd: dir }).catch((e) => e))).toContain("has no `source`")
  })

  test("rejects an unknown environment", async () => {
    const dir = await project({}, {})

    const error = await runEnvPull({ cwd: dir, env: "staging" }).catch((failure) => failure)

    expect(String(error)).toContain("--env dev or --env prod")
  })

  describe("when a deploy can't reach the source", () => {
    async function server(state: SourceState, vars: Record<string, string>, dotEnvFile?: string) {
      const dir = await project(state, vars)
      const tokenFile = join(dir, "env-token")
      await writeFile(tokenFile, "server-token")
      if (dotEnvFile !== undefined) await writeFile(join(dir, ".env"), dotEnvFile)
      return { dir, pull: () => runEnvPull({ cwd: dir, env: "prod", tokenFile }) }
    }

    // Reproduce: always rethrow in pullEnv's catch.
    test("keeps a complete generated .env, and says so", async () => {
      const { dir, pull } = await server({ fail: "down" }, { A: "required" }, GENERATED_ENV)

      const result = await runInProcess(pull)

      expect(result.error).toBeUndefined()
      expect(result.output).toContain("Kept the current .env")
      expect(await dotEnv(dir)).toBe(GENERATED_ENV)
    })

    test("fails when the current .env lacks a declared name", async () => {
      const { pull } = await server({ fail: "down" }, { NEW: "required" }, GENERATED_ENV)

      expect(await pull().catch((failure) => failure)).toBeInstanceOf(EnvSourceUnreachableError)
    })

    test("fails when the current .env is hand-written", async () => {
      const { pull } = await server({ fail: "down" }, { A: "required" }, "A=mine\n")

      expect(await pull().catch((failure) => failure)).toBeInstanceOf(EnvSourceUnreachableError)
    })

    test("fails when there is no .env", async () => {
      const { pull } = await server({ fail: "down" }, {})

      expect(await pull().catch((failure) => failure)).toBeInstanceOf(EnvSourceUnreachableError)
    })

    // Reproduce: drop the instanceof check from `riding` in pullEnv. A revoked token then deploys.
    test("still fails when the source refuses, even with a complete .env", async () => {
      const { pull } = await server({ fail: "refused" }, { A: "required" }, GENERATED_ENV)

      expect(String(await pull().catch((failure) => failure))).toContain("refused")
    })
  })

  test("a laptop that can't reach the source gets the failure, not a stale file", async () => {
    const dir = await project({ fail: "down" }, { A: "required" })
    await writeFile(join(dir, ".env"), GENERATED_ENV)

    expect(await runEnvPull({ cwd: dir }).catch((f) => f)).toBeInstanceOf(EnvSourceUnreachableError)
  })
})

describe("sixb dev", () => {
  // Reproduce: remove the Object.assign in pullIntoThisProcess. The processes `sixb dev` starts
  // inherit this one's environment, so they would run on the old value.
  test("a pull reaches this process, with .env.local still winning", async () => {
    const dir = await project(
      { dev: { STALE: "new", ADDED: "added", OVERRIDDEN: "from-source" } },
      { ADDED: "required" }
    )
    await writeFile(join(dir, ".env.local"), "OVERRIDDEN=from-local\n")
    const config = await loadEnvConfig(dir)
    if (!config?.source) throw new Error("The fixture has a source.")
    const { source } = config

    let seen: Record<string, string | undefined> = {}
    await runInProcess(async () => {
      process.env.STALE = "old"
      await pullIntoThisProcess(dir, config, source)
      seen = { ...process.env }
    })

    expect(seen.STALE).toBe("new")
    expect(seen.ADDED).toBe("added")
    expect(seen.OVERRIDDEN).toBe("from-local")
  })

  test("still names what's missing when .env.local empties it", async () => {
    const dir = await project({ dev: { A: "value" } }, { A: "required" })
    await writeFile(join(dir, ".env.local"), "A=\n")
    const config = await loadEnvConfig(dir)
    if (!config?.source) throw new Error("The fixture has a source.")
    const { source } = config

    const result = await runInProcess(() => pullIntoThisProcess(dir, config, source))

    expect(String(result.error)).toContain("Missing A,")
  })

  test("without a terminal it says to pull instead of asking", async () => {
    const dir = await project(
      { dev: { SIXB_ENV_TEST_DEV: "value" } },
      { SIXB_ENV_TEST_DEV: "required" }
    )

    const result = await runInProcess(() => {
      // Under `bun test` in a terminal, this would otherwise wait for an answer.
      process.env.CI = "1"
      return assertDevEnv(dir)
    })

    expect(String(result.error)).toContain("Missing SIXB_ENV_TEST_DEV,")
    expect(errorRemediation(result.error)).toContain("sixb env pull")
  })
})

describe("sixb env set", () => {
  const set = (cwd: string, args: readonly string[], stdin?: string) =>
    runCliToCompletion({
      cmd: [process.execPath, CLI_ENTRY, "env", "set", ...args],
      cwd,
      stdin: stdin ?? "",
      timeoutMs: FAST_CLI_TIMEOUT_MS,
    })

  test("reads the value from standard input, without printing it", async () => {
    const dir = await project({ prod: { KEEP: "kept" } }, { NEW_KEY: "required" })

    const result = await set(dir, ["NEW_KEY", "--env", "prod"], "the-secret-value\n")

    expect(result.exitCode).toBe(0)
    expect(result.stdout).toContain("Set NEW_KEY")
    expect(result.stdout).not.toContain("the-secret-value")
    expect((await sourceState(dir)).prod).toEqual({ KEEP: "kept", NEW_KEY: "the-secret-value" })
  })

  test("keeps a value's own newlines, dropping only the one that ended the input", async () => {
    const dir = await project({}, {})

    await set(dir, ["PEM", "--env", "dev"], "line1\nline2\n")

    expect((await sourceState(dir)).dev?.PEM).toBe("line1\nline2")
  })

  test("says when the name isn't declared", async () => {
    const dir = await project({}, {})

    const result = await set(dir, ["UNDECLARED", "--env", "dev"], "value")

    expect(result.exitCode).toBe(0)
    expect(result.stdout).toContain("Add UNDECLARED to sixb.env.ts")
  })

  test.each([
    ["no environment", ["NAME"], "value", "--env dev or --env prod"],
    ["a bad name", ["BAD-NAME", "--env", "dev"], "value", "not a variable name"],
    ["an empty value", ["NAME", "--env", "dev"], "", "needs a value"],
  ])("rejects %s", async (_case, args, stdin, message) => {
    const dir = await project({}, {})

    const result = await set(dir, args, stdin)

    expect(result.exitCode).not.toBe(0)
    expect(result.stdout + result.stderr).toContain(message)
    expect((await sourceState(dir)).dev).toBeUndefined()
  })

  // Reproduce: quote the argument in the error. This is the easiest slip to make with the command,
  // and it would print the secret into a CI log.
  test("never prints KEY=value typed as the name", async () => {
    const dir = await project({}, {})

    const result = await set(dir, ["API_KEY=the-secret-value", "--env", "dev"], "")

    expect(result.exitCode).not.toBe(0)
    expect(result.stdout + result.stderr).not.toContain("the-secret-value")
    expect((await sourceState(dir)).dev).toBeUndefined()
  })

  test("a value can't be passed as an argument", () => {
    expect(() => parseCliArgs(["env", "set", "NAME", "value", "--env", "dev"])).toThrow()
  })
})

describe("sixb env status", () => {
  test("shows which values exist, never what they are", async () => {
    const dir = await project(
      {
        dev: { BOTH: "the-secret-value", EXTRA: "1" },
        prod: { BOTH: "the-secret-value", PROD_ONLY: "2" },
      },
      { BOTH: "required", PROD_ONLY: "prod", LATER: "required", MAYBE: "optional" }
    )

    const result = await runInProcess(() => runEnvStatus({ cwd: dir }))
    const line = (name: string) =>
      result.output
        .split("\n")
        .find((text) => text.includes(name))
        ?.replace(/\s+/g, " ")
        .trim()

    expect(line("BOTH")).toBe("BOTH ✓ ✓")
    expect(line("PROD_ONLY")).toBe("PROD_ONLY – ✓")
    expect(line("LATER")).toBe("LATER ✗ missing ✗ missing")
    expect(line("MAYBE")).toBe("MAYBE – –")
    expect(line("EXTRA")).toBe("EXTRA ✓ – not in sixb.env.ts")
    expect(result.output).toContain("2 values missing")
    expect(result.output).not.toContain("the-secret-value")
    expect(result.exitCode).toBe(1)
  })

  test("passes when everything required is set", async () => {
    const dir = await project({ dev: { A: "1" }, prod: { A: "2" } }, { A: "required" })

    const result = await runInProcess(() => runEnvStatus({ cwd: dir }))

    expect(result.output).toContain("Everything sixb.env.ts requires is set")
    expect(result.exitCode ?? 0).toBe(0)
  })

  test("marks an environment this person can't read instead of calling it missing", async () => {
    const dir = await project({ dev: { A: "1" }, noAccess: ["prod"] }, { A: "required" })

    const result = await runInProcess(() => runEnvStatus({ cwd: dir }))

    expect(result.output).toContain("no access")
    expect(result.output).not.toContain("missing")
    expect(result.output).toContain("set where you have access")
  })

  test("reports the failure when neither environment answers", async () => {
    const dir = await project({ fail: "refused" }, {})

    const error = await runEnvStatus({ cwd: dir }).catch((failure) => failure)

    expect(String(error)).toContain("refused")
  })
})

describe("sixb env init", () => {
  async function fresh(): Promise<string> {
    const dir = await mkdtemp(join(tmpdir(), "sixb-env-init-"))
    projects.push(dir)
    const dopplerPackage = join(dir, "node_modules/@sixb/env-doppler")
    await mkdir(dopplerPackage, { recursive: true })
    await symlink(CORE_PACKAGE, join(dir, "node_modules/@sixb/core"))
    await writeFile(
      join(dopplerPackage, "package.json"),
      JSON.stringify({ name: "@sixb/env-doppler", type: "module", exports: "./index.ts" })
    )
    await writeFile(join(dopplerPackage, "index.ts"), FAKE_DOPPLER)
    await writeFile(join(dir, "source.json"), "{}")
    return dir
  }

  // Stands in for the published package, keeping its state beside the project.
  const FAKE_DOPPLER = `
    const file = new URL("../../../source.json", import.meta.url).pathname
    const load = async () => JSON.parse(await Bun.file(file).text())
    export const doppler = ({ project }) => ({
      async names(env) { return Object.keys((await load())[env] ?? {}) },
      async read(env) { return (await load())[env] ?? {} },
      async write(env, values) {
        const state = await load()
        await Bun.write(file, JSON.stringify({ ...state, project, [env]: { ...state[env], ...values } }))
      },
    })
  `

  test("uploads both files and writes sixb.env.ts with a first guess at each rule", async () => {
    const dir = await fresh()
    await writeFile(join(dir, ".env"), "BOTH=dev\nDEV_ONLY=1\nEMPTY=\n")
    await writeFile(join(dir, ".env.prod"), "BOTH=prod\nPROD_ONLY=2\nEMPTY=\n")

    const result = await runInProcess(() =>
      runEnvInit({ cwd: dir, project: "client-a", dev: ".env", prod: ".env.prod" })
    )

    expect(result.error).toBeUndefined()
    expect(result.output).toContain("Uploaded 3 variables to dev and 3 variables to prod")
    expect(result.output).toContain("Wrote sixb.env.ts with 4 names")
    const state = await sourceState(dir)
    expect(state.dev).toEqual({ BOTH: "dev", DEV_ONLY: "1", EMPTY: "" })
    expect(state.prod).toEqual({ BOTH: "prod", PROD_ONLY: "2", EMPTY: "" })

    const written = await readFile(join(dir, "sixb.env.ts"), "utf8")
    expect(written).toContain('doppler({ project: "client-a" })')
    expect((await loadEnvConfig(dir))?.vars).toEqual({
      BOTH: "required",
      DEV_ONLY: "optional",
      EMPTY: "optional",
      PROD_ONLY: "prod",
    })
  })

  // Reproduce: return `required` for every name with a value in each file given. `sixb dev` then
  // stops on every prod variable until dev has it too.
  test("with only a prod file, its names are required in prod alone", async () => {
    const dir = await fresh()
    await writeFile(join(dir, ".env.prod"), "A=1\n")

    await runInProcess(() => runEnvInit({ cwd: dir, project: "client-a", prod: ".env.prod" }))

    expect((await loadEnvConfig(dir))?.vars).toEqual({ A: "prod" })
  })

  // Reproduce: remove uploadableValues. `foo-bar: "optional",` makes sixb.env.ts a syntax error,
  // after the upload, and every sixb command that loads it fails.
  test("stops on a name sixb.env.ts couldn't declare, sending nothing", async () => {
    const dir = await fresh()
    await writeFile(join(dir, ".env"), "GOOD=1\nfoo-bar=2\n")

    const error = await runEnvInit({ cwd: dir, project: "client-a", dev: ".env" }).catch((f) => f)

    expect(String(error)).toContain("foo-bar")
    expect((await sourceState(dir)).dev).toBeUndefined()
    expect(await Bun.file(join(dir, "sixb.env.ts")).exists()).toBe(false)
  })

  test("leaves out the token this machine reaches Doppler with", async () => {
    const dir = await fresh()
    await writeFile(join(dir, ".env"), "A=1\nDOPPLER_TOKEN=dp.pt.secret\n")

    await runInProcess(() => runEnvInit({ cwd: dir, project: "client-a", dev: ".env" }))

    expect((await sourceState(dir)).dev).toEqual({ A: "1" })
    expect((await loadEnvConfig(dir))?.vars).toEqual({ A: "required" })
  })

  test("with one file, its names are required", async () => {
    const dir = await fresh()
    await writeFile(join(dir, ".env"), "A=1\n")

    await runInProcess(() => runEnvInit({ cwd: dir, project: "client-a", dev: ".env" }))

    expect((await loadEnvConfig(dir))?.vars).toEqual({ A: "required" })
  })

  // Reproduce: remove the conflict loop in runEnvInit. The dashboard's value is then overwritten.
  test("changes nothing when the source already has another value", async () => {
    const dir = await fresh()
    await writeFile(join(dir, "source.json"), JSON.stringify({ prod: { A: "dashboard-value" } }))
    await writeFile(join(dir, ".env"), "NEW=1\n")
    await writeFile(join(dir, ".env.prod"), "A=file-value\n")

    const error = await runEnvInit({
      cwd: dir,
      project: "client-a",
      dev: ".env",
      prod: ".env.prod",
    }).catch((failure) => failure)

    expect(String(error)).toContain("already has other values in prod for A")
    expect(String(error)).not.toContain("dashboard-value")
    expect((await sourceState(dir)).dev).toBeUndefined()
    expect(await Bun.file(join(dir, "sixb.env.ts")).exists()).toBe(false)
  })

  test("can run again after an upload that didn't finish", async () => {
    const dir = await fresh()
    await writeFile(join(dir, "source.json"), JSON.stringify({ dev: { A: "1" } }))
    await writeFile(join(dir, ".env"), "A=1\n")

    await runInProcess(() => runEnvInit({ cwd: dir, project: "client-a", dev: ".env" }))

    expect(await Bun.file(join(dir, "sixb.env.ts")).exists()).toBe(true)
  })

  test.each([
    ["sixb.env.ts exists", { config: true, file: ".env" }, "already exists"],
    ["no file is given", { config: false, file: undefined }, "Say where the current values are"],
    ["the file is missing", { config: false, file: ".nope" }, ".nope does not exist"],
  ])("stops when %s", async (_case, { config, file }, message) => {
    const dir = await fresh()
    if (config) await writeFile(join(dir, "sixb.env.ts"), "export default { vars: {} }\n")

    const error = await runEnvInit({
      cwd: dir,
      project: "client-a",
      ...(file === undefined ? {} : { dev: file }),
    }).catch((failure) => failure)

    expect(String(error)).toContain(message)
  })

  test("says to install the package when the project doesn't have it", async () => {
    const dir = await mkdtemp(join(tmpdir(), "sixb-env-init-"))
    projects.push(dir)
    await writeFile(join(dir, ".env"), "A=1\n")

    const error = await runEnvInit({ cwd: dir, project: "client-a", dev: ".env" }).catch((f) => f)

    expect(errorRemediation(error)).toBe("bun add @sixb/env-doppler")
  })
})

