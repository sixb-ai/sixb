import type { FileRef } from "../../blob-storage/types"
import type { ReadonlyJsonObject, ReadonlyJsonValue } from "../../json"
import type { ModelReasoning } from "../../models/language-model"

/** Coverage of normalized usage. Complete means both token totals are known; duration alone is partial. */
export type AiUsageReportingStatus = "complete" | "partial" | "unavailable"

/** Provider-neutral usage accepted at the model-call boundary. */
export interface AiModelCallUsageInput {
  /** Audio content duration in milliseconds, rounded to the nearest millisecond. Not billed duration. */
  readonly audioDurationMs?: number
  readonly inputTokens?: number
  readonly outputTokens?: number
  readonly uncachedInputTokens?: number
  readonly cacheReadInputTokens?: number
  readonly cacheWriteInputTokens?: number
  readonly textOutputTokens?: number
  readonly reasoningOutputTokens?: number
  /** Output tokens that encode generated images, within outputTokens. */
  readonly imageOutputTokens?: number
  /** Output tokens that encode generated audio, within outputTokens. */
  readonly audioOutputTokens?: number
  /** Images the call returned. */
  readonly outputImages?: number
  /** Input characters, counted by the provider's own billing rule. */
  readonly inputCharacters?: number
  /** Milliseconds of video the call returned, every clip together, as the provider bills them. */
  readonly outputVideoMs?: number
}

/** Normalized usage for one completed model call. Token details overlap their input/output totals. */
export interface AiModelCallUsage extends AiModelCallUsageInput {
  /** Present only when both input and output totals are known. */
  readonly totalTokens?: number
  readonly reportingStatus: AiUsageReportingStatus
}

/** Aggregated usage and call presence for one durable execution. */
export interface AiUsageExecutionSummary {
  /** Number of idempotent model-call ledger records included across every delivery attempt. */
  readonly modelCallCount: number
  /** Unavailable with a positive call count means the provider reported no normalized counts. */
  readonly usage: AiModelCallUsage
}

/** Input for an idempotent model-call ledger append. */
export interface RecordAiModelCallInput {
  /** Absent for historical calls whose kind was not captured. */
  readonly modelKind?: import("../../models/definitions").ModelKind
  readonly providerIds?: import("../../models/events").ModelProviderIds
  readonly id: string
  readonly projectId: string
  /** Immutable execution-ledger record that owns this provider call. */
  readonly executionId: string
  /** Queue delivery attempt that made the provider call. */
  readonly attempt: number
  /** Stable call ID generated by the owned model loop. */
  readonly callId: string
  /**
   * Durable group memberships snapshotted when the parent run was admitted. The requester itself
   * is read from the immutable execution record.
   */
  readonly requesterGroupIds: readonly string[]
  /** Provider contract that handled the call, such as `anthropic` or `vercel-ai-gateway`. */
  readonly providerId: string
  readonly requestedModelId: string
  /** Provider-neutral reasoning preference used for this call, when explicitly configured. */
  readonly requestedReasoning?: ModelReasoning
  /** Provider-returned model identity when the capture path exposes it. */
  readonly responseModelId?: string
  /** Provider-returned response ID used for later usage and cost reconciliation. */
  readonly responseId: string
  readonly usage: AiModelCallUsageInput
  readonly rawUsage?: ReadonlyJsonObject
  /** When the provider call completed, used for historical pricing and accounting periods. */
  readonly occurredAt: Date
  readonly recordedAt?: Date
}

/** Immutable accounting record for one completed provider model call. */
export interface AiModelCallUsageRecord extends RecordAiModelCallInput {
  readonly usage: AiModelCallUsage
  readonly recordedAt: Date
}

export interface RecordAiModelCallResult {
  readonly record: AiModelCallUsageRecord
  /** False when the idempotency key already existed and its record was returned. */
  readonly created: boolean
}

export interface SummarizeAiUsageExecutionInput {
  readonly projectId: string
  readonly executionId: string
}

export interface SummarizeAiUsageExecutionsInput {
  readonly projectId: string
  readonly executionIds: readonly string[]
}

export interface GetLatestAiModelCallForExecutionInput {
  readonly projectId: string
  readonly executionId: string
}

/**
 * The files one completed call produced, recorded once they are stored. The execution that made
 * the call decides who may read them.
 */
export interface AiModelCallFilesRecord {
  readonly projectId: string
  readonly executionId: string
  readonly callId: string
  readonly files: readonly FileRef[]
  readonly recordedAt: Date
}

export type RecordAiModelCallFilesInput = Omit<AiModelCallFilesRecord, "recordedAt"> & {
  readonly recordedAt?: Date
}

export interface GetAiModelCallFilesInput {
  readonly projectId: string
  readonly callId: string
}

export type AiModelCallOperationStatus = "pending" | "completed" | "failed"

/**
 * A model call the provider keeps running after the request that started it, such as a video
 * generation: what a later request needs to check on it and record how it ended.
 */
export interface AiModelCallOperationRecord {
  readonly projectId: string
  readonly callId: string
  /** The execution attempt that admitted the call, which its ledger record belongs to. */
  readonly executionId: string
  readonly attempt: number
  readonly modelKind: import("../../models/definitions").ModelKind
  readonly providerId: string
  readonly modelId: string
  /** The provider's handle on the running call, opaque to Sixb; absent until it accepted the call. */
  readonly operation?: ReadonlyJsonValue
  /** The request facts that price the call once it ends, owned by the model kind's runtime. */
  readonly request: ReadonlyJsonObject
  /** Whether admission reserved budget that recording the call must reconcile. */
  readonly reserved: boolean
  readonly status: AiModelCallOperationStatus
  /** Why the provider failed the call, when it did. */
  readonly error?: string
  /**
   * What the call reported, such as its usage and cost, owned by the kind's runtime. Kept while
   * pending once the call is in the ledger, before its files are stored.
   */
  readonly result?: ReadonlyJsonObject
  readonly createdAt: Date
  readonly settledAt?: Date
}

export type CreateAiModelCallOperationInput = Omit<
  AiModelCallOperationRecord,
  "operation" | "status" | "error" | "result" | "createdAt" | "settledAt"
> & {
  readonly createdAt?: Date
}

export interface StartAiModelCallOperationInput {
  readonly projectId: string
  readonly callId: string
  /** The provider's handle on the running call. */
  readonly operation: ReadonlyJsonValue
  /** The request facts as the provider accepted the call, in place of those kept at creation. */
  readonly request: ReadonlyJsonObject
}

export interface RecordAiModelCallOperationResultInput {
  readonly projectId: string
  readonly callId: string
  readonly result: ReadonlyJsonObject
}

export interface SettleAiModelCallOperationInput {
  readonly projectId: string
  readonly callId: string
  readonly status: Exclude<AiModelCallOperationStatus, "pending">
  readonly error?: string
  readonly result: ReadonlyJsonObject
  readonly settledAt?: Date
}

/** Durable, provider-neutral accounting for completed model calls. */
export interface AiUsageStorage {
  /**
   * Append one model-call record idempotently. The identity is project, execution ID, attempt, call
   * ID, and response ID; retrying that identity returns the existing record with `created: false`.
   */
  recordModelCall(input: RecordAiModelCallInput): Promise<RecordAiModelCallResult>

  /** Latest completed provider call for one execution, ordered by occurrence and stable id. */
  getLatestForExecution(
    input: GetLatestAiModelCallForExecutionInput
  ): Promise<AiModelCallUsageRecord | null>

  /** Aggregate normalized usage and call presence across every attempt of one execution. */
  summarizeExecution(input: SummarizeAiUsageExecutionInput): Promise<AiUsageExecutionSummary>

  /**
   * Aggregate multiple executions in one storage read. Results have the same length and order as
   * `executionIds`. Executions without ledger records have a zero model-call count and unavailable
   * usage.
   */
  summarizeExecutions(
    input: SummarizeAiUsageExecutionsInput
  ): Promise<readonly AiUsageExecutionSummary[]>

  /**
   * Record the files a call produced, once per project and call ID. Recording the same call again
   * returns the first record; naming another execution for it is refused.
   */
  recordModelCallFiles(input: RecordAiModelCallFilesInput): Promise<AiModelCallFilesRecord>

  getModelCallFiles(input: GetAiModelCallFilesInput): Promise<AiModelCallFilesRecord | null>

  /**
   * Keep a call before the provider starts it, once per project and call ID, so a call the
   * provider bills always has a record to settle.
   */
  createModelCallOperation(
    input: CreateAiModelCallOperationInput
  ): Promise<AiModelCallOperationRecord>

  /**
   * Keep the provider's handle once it accepted the call. Only a pending call without one takes
   * it; returns the record as it now stands, or null when no such call exists.
   */
  startModelCallOperation(
    input: StartAiModelCallOperationInput
  ): Promise<AiModelCallOperationRecord | null>

  getModelCallOperation(input: GetAiModelCallFilesInput): Promise<AiModelCallOperationRecord | null>

  /**
   * Keep what a pending call reported once it is in the ledger, before its files are stored, so a
   * call settled without them still reports it. The first result wins; returns the record as it
   * now stands, or null when no such call exists.
   */
  recordModelCallOperationResult(
    input: RecordAiModelCallOperationResultInput
  ): Promise<AiModelCallOperationRecord | null>

  /**
   * Record how a pending call ended. The first settlement wins: settling it again returns that
   * record unchanged. Null when no such call exists.
   */
  settleModelCallOperation(
    input: SettleAiModelCallOperationInput
  ): Promise<AiModelCallOperationRecord | null>
}
