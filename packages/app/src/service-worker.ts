/** Where the service worker is served: a Sixb name, so a project's own `public/sw.js` keeps its. */
export const SERVICE_WORKER_PATH = "/sixb-service-worker.js"

/**
 * Paths the app's origin keeps for the API, sign-in, docs and shared links. The worker leaves them
 * to the network, as the app's link handling does.
 */
export const RESERVED_PATH_PREFIXES = ["/api", "/auth", "/ws", "/docs", "/shared"] as const

/**
 * Names `buildApp` gives entries, chunks and assets: a content hash keeps each one's contents fixed
 * under its URL, so the server caches them forever and the worker can serve them without asking.
 */
export const IMMUTABLE_ASSET_PATTERN =
  /^(?:(?:app|shared|chunk)-[a-z0-9]+|(?:chunk|asset)-.+-[a-z0-9]+)\.[a-z0-9]+(?:\.map)?$/

/** How long a page waits for the network before opening from the device instead. */
const NAVIGATION_TIMEOUT_MS = 3000

export interface ServiceWorkerOptions {
  /** Changes with every build, so a deploy replaces what the device keeps. */
  readonly version: string
  /** Same-origin files the app needs to open: its entry script and stylesheet, and its icons. */
  readonly precache: readonly string[]
}

/**
 * The service worker a production build ships. It keeps the app on the device, so the installed
 * app opens on a slow connection or none:
 *
 * - A page goes to the network first, and opens from the device when the network fails or takes
 *   longer than three seconds. Every page is the same app shell, saved from `/` once per version.
 * - A hashed file comes from the device once saved; any other file of the app's comes from the
 *   network, and from the device when the network fails. Each is saved as it loads.
 * - Other origins, such as a separately served API, and the reserved paths pass through untouched.
 *
 * Installing saves the shell and the files it opens with; a new version takes over at once and
 * clears the last one's files. The page's data still comes from the API.
 */
export function renderServiceWorker(options: ServiceWorkerOptions): string {
  return `// Generated by Sixb: the app's service worker. See @sixb/app's service-worker.ts.
const CACHE_PREFIX = "sixb-app-"
const CACHE = CACHE_PREFIX + ${JSON.stringify(options.version)}
const SHELL = "/"
const PRECACHE = ${JSON.stringify(options.precache)}
const RESERVED = ${JSON.stringify(RESERVED_PATH_PREFIXES)}
const IMMUTABLE = ${IMMUTABLE_ASSET_PATTERN.toString()}
const NAVIGATION_TIMEOUT_MS = ${NAVIGATION_TIMEOUT_MS}

self.addEventListener("install", (event) => {
  // Best effort: a file that fails to save is saved when the app next loads it.
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) =>
        Promise.allSettled([
          fetch(new Request(SHELL, { cache: "reload" })).then((response) =>
            isShell(response) ? cache.put(SHELL, response) : undefined
          ),
          ...PRECACHE.map((path) => cache.add(new Request(path, { cache: "reload" }))),
        ])
      )
      .then(() => self.skipWaiting())
  )
})

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  )
})

self.addEventListener("fetch", (event) => {
  const request = event.request
  if (request.method !== "GET" || request.headers.has("range")) return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin || isReserved(url.pathname)) return

  if (request.mode === "navigate") {
    event.respondWith(page(event, url))
  } else {
    event.respondWith(file(event, url))
  }
})

function page(event, url) {
  let saving = Promise.resolve()
  const network = fetch(event.request).then((response) => {
    // Only "/" refreshes the shell: another address may be a page of the project's own.
    if (url.pathname === SHELL && isShell(response)) {
      const copy = response.clone()
      saving = caches.open(CACHE).then((cache) => cache.put(SHELL, copy))
    }
    return response
  })
  event.waitUntil(network.then(() => saving, () => undefined))

  const offline = network.catch(() => savedShell().then((saved) => saved ?? Response.error()))
  const slow = delay(NAVIGATION_TIMEOUT_MS)
    .then(savedShell)
    .then((saved) => saved ?? offline)
  return Promise.race([offline, slow])
}

async function file(event, url) {
  const cache = await caches.open(CACHE)
  const immutable = IMMUTABLE.test(url.pathname.split("/").pop() ?? "")
  if (immutable) {
    const saved = await cache.match(event.request)
    if (saved) return saved
  }
  try {
    const response = await fetch(event.request)
    if (response.ok && response.type === "basic") {
      event.waitUntil(cache.put(event.request, response.clone()))
    }
    return response
  } catch (error) {
    const saved = await cache.match(event.request)
    if (saved) return saved
    throw error
  }
}

function isShell(response) {
  return (
    response.ok &&
    !response.redirected &&
    response.type === "basic" &&
    (response.headers.get("content-type") ?? "").includes("text/html")
  )
}

function savedShell() {
  return caches.open(CACHE).then((cache) => cache.match(SHELL))
}

function isReserved(pathname) {
  return RESERVED.some((prefix) => pathname === prefix || pathname.startsWith(prefix + "/"))
}

function delay(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms))
}
`
}
