import type { DeployHttpServiceName, DeployRelease, DeployReleaseService } from "@sixb/core/deploy"
import type { DeploymentLayout, ReleaseLayout, SlotLayout } from "./layout"
import type { ProcessManifest } from "./server/manifest"
import { drainKillTimeoutMs, INTERRUPT_LEAD_MS } from "./server/supervisor"
import { shellQuote } from "./shell"
import { renderUpdatePage } from "./update-page"

const GENERATED = "Generated by sixb deploy. Changes are replaced on the next deploy."

/** Rewrites a release's HTTP services to listen on the given slot's loopback ports. */
export function releaseForSlot(
  release: DeployRelease,
  ports: Readonly<Record<DeployHttpServiceName, number>>
): DeployRelease {
  return {
    ...release,
    services: release.services.map((service) => {
      if (!service.http || (service.name !== "api" && service.name !== "app")) {
        return service
      }
      const port = ports[service.name]
      return {
        ...service,
        command: {
          ...service.command,
          args: replacePortArg(service.command.args, port),
        },
        http: {
          ...service.http,
          port,
        },
      }
    }),
  }
}

function replacePortArg(args: readonly string[], port: number): string[] {
  const next = [...args]
  const index = next.indexOf("--port")
  if (index !== -1 && index + 1 < next.length) {
    next[index + 1] = String(port)
  }
  return next
}

/** The supervisor's view of a release in one slot: absolute commands, full environments. */
export function renderProcessManifest(
  release: DeployRelease,
  input: {
    readonly layout: DeploymentLayout
    readonly slot: SlotLayout
    readonly release: ReleaseLayout
    readonly holdExclusive: boolean
  }
): ProcessManifest {
  const project = input.release.project
  const sixb = `${project}/node_modules/.bin/sixb`
  return {
    version: 1,
    name: release.name,
    slot: input.slot.slot,
    ...(input.holdExclusive ? { holdExclusive: true } : {}),
    cwd: project,
    runDir: input.slot.runDir,
    logDir: input.slot.logDir,
    releasePath: input.layout.releaseRecord,
    env: release.env,
    services: release.services.map((service) => ({
      name: service.name,
      kind: service.kind,
      processName: `${release.name}-${service.name}`,
      command: input.release.bun,
      args:
        service.command.program === "sixb"
          ? [sixb, ...service.command.args]
          : [...service.command.args],
      env: serviceEnvWithDrain(service),
      instances: service.instances,
      killTimeoutMs: service.process.killTimeoutMs,
      restartDelayMs: service.process.restartDelayMs,
      ...(service.process.maxMemory ? { maxMemory: service.process.maxMemory } : {}),
    })),
  }
}

/**
 * A retiring `api` or `workers` drains until the supervisor's SIGINT, so it finishes its work on
 * its own rather than being cut short. The window follows the service's own kill timeout.
 */
function serviceEnvWithDrain(service: DeployReleaseService): Record<string, string> {
  if (
    (service.name === "api" || service.name === "workers") &&
    service.env.SIXB_DRAIN_TIMEOUT_MS === undefined
  ) {
    const drainTimeoutMs = drainKillTimeoutMs(service.process.killTimeoutMs) - INTERRUPT_LEAD_MS

    return {
      SIXB_DRAIN_TIMEOUT_MS: String(drainTimeoutMs),
      ...service.env,
    }
  }
  return { ...service.env }
}

/** What a slot's service runs: its release's supervisor, with that release's Bun. */
export function renderLauncher(release: ReleaseLayout, slot: SlotLayout): string {
  return renderServerCommand(release, ["supervise"], slot.manifest)
}

/** What `status`, `logs` and the other operations run: the live release's server half. */
export function renderCtl(release: ReleaseLayout, slot: SlotLayout): string {
  return renderServerCommand(release, [], slot.manifest, '"$@" ')
}

function renderServerCommand(
  release: ReleaseLayout,
  args: readonly string[],
  manifest: string,
  passThrough = ""
): string {
  const bin = `${release.project}/node_modules/.bin/sixb-deploy-ssh`
  const command = [release.bun, bin, ...args].map(shellQuote).join(" ")
  return [
    "#!/bin/sh",
    `# ${GENERATED}`,
    // A process that runs `bun` or `node` (a dependency's script) finds the release's Bun.
    `PATH=${shellQuote(release.bunDir)}:"$PATH"; export PATH`,
    `exec ${command} ${passThrough}--manifest ${shellQuote(manifest)}`,
    "",
  ].join("\n")
}

/**
 * The slot service's template: `sixb-<name>@blue` and `sixb-<name>@green` each run their slot's
 * launcher. Lingering starts the live slot's at boot. Stopping one signals only the supervisor,
 * which lets its HTTP services and workers drain before systemd's stop timeout.
 */
export function renderSlotUnit(release: DeployRelease, layout: DeploymentLayout): string {
  const killTimeoutMs = Math.max(
    ...release.services.map((service) => drainKillTimeoutMs(service.process.killTimeoutMs))
  )
  return [
    `# ${GENERATED}`,
    "[Unit]",
    `Description=Sixb deployment ${release.name}, %i slot`,
    "",
    "[Service]",
    "Type=simple",
    `WorkingDirectory=${systemdValue(layout.root)}`,
    "Environment=PATH=/usr/local/bin:/usr/bin:/bin",
    `ExecStart=${systemdValue(layout.deployDir)}/%i`,
    "Restart=always",
    "RestartSec=2",
    "KillMode=mixed",
    "KillSignal=SIGTERM",
    `TimeoutStopSec=${Math.ceil(killTimeoutMs / 1000) + 15}`,
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n")
}

/** One site per HTTP service, forwarded to the active slot's loopback port. */
export function renderCaddySnippet(release: DeployRelease): string {
  const sites = release.services.flatMap((service) => {
    if (!service.http) return []
    const pages = service.name === "app"
    return [
      [
        `${service.http.domain} {`,
        ...(service.name === "api" ? compressJson() : []),
        `\treverse_proxy ${service.http.host}:${service.http.port} {`,
        "\t\tlb_try_duration 5s",
        ...(service.name === "api" ? keepWebSocketsThroughReload(service) : []),
        "\t}",
        ...(pages ? updatePageOnProxyErrors() : []),
        "}",
      ].join("\n"),
    ]
  })
  return [`# ${GENERATED}`, "", sites.join("\n\n"), ""].join("\n")
}

/**
 * A reload closes every WebSocket Caddy proxies unless it is told to wait, and each deploy reloads
 * Caddy before the old API retires. Kept open, a browser's socket stays on the retiring API, which
 * closes it with 1012 so the page reconnects without showing a drop. The wait covers the API's
 * whole retiring window; the API closes its sockets as soon as it starts draining.
 */
function keepWebSocketsThroughReload(service: DeployReleaseService): string[] {
  const seconds = drainKillTimeoutMs(service.process.killTimeoutMs) / 1000
  return [`\t\tstream_close_delay ${seconds}s`]
}

/**
 * The API never compresses its responses, and an object query page is easily a megabyte of
 * JSON that compresses about twentyfold. Only complete JSON answers are encoded: the
 * WebSocket upgrade and anything else streamed through the API stay as they are, since an
 * encoder buffers what it writes. A 206 keeps its byte range of the stored file intact, and the
 * app's assets are already precompressed.
 */
function compressJson(): string[] {
  return [
    "\tencode {",
    "\t\tzstd",
    "\t\tgzip",
    "\t\tmatch {",
    "\t\t\tstatus 200",
    "\t\t\theader Content-Type application/json*",
    "\t\t}",
    "\t}",
  ]
}

/**
 * While the app is down — during an outage — a browser asking for a page gets the update page
 * instead of Caddy's bare error. Other requests keep the error.
 */
function updatePageOnProxyErrors(): string[] {
  return [
    "\thandle_errors 502 503 504 {",
    "\t\t@page {",
    "\t\t\tmethod GET",
    "\t\t\theader Accept *text/html*",
    "\t\t}",
    "\t\thandle @page {",
    '\t\t\theader Content-Type "text/html; charset=utf-8"',
    '\t\t\theader Cache-Control "no-store"',
    '\t\t\theader Retry-After "10"',
    "\t\t\trespond 503 {",
    "\t\t\t\tbody <<HTML",
    ...renderUpdatePage()
      .split("\n")
      .map((line) => `\t\t\t\t${line}`),
    "\t\t\t\tHTML",
    "\t\t\t}",
    "\t\t}",
    "\t\thandle {",
    '\t\t\trespond "Service temporarily unavailable" {err.status_code}',
    "\t\t}",
    "\t}",
  ]
}

function systemdValue(value: string): string {
  return value.replace(/%/g, "%%").replace(/\s/g, "\\x20")
}
