import type { DeployHttpServiceName, DeployRelease, DeployReleaseService } from "@sixb/core/deploy"
import type { DeploymentLayout, DeploySlot } from "./layout"
import type { ProcessManifest } from "./server/manifest"
import { RETIRING_KILL_TIMEOUT_MS } from "./server/supervisor"
import { shellQuote } from "./shell"
import { renderUpdatePage } from "./update-page"

const GENERATED = "Generated by sixb deploy. Changes are replaced on the next deploy."
/** Leaves 10 s before `RETIRING_KILL_TIMEOUT_MS` for SIGINT escalation and finalization. */
const RETIRING_DRAIN_TIMEOUT_MS = RETIRING_KILL_TIMEOUT_MS - 10_000

export type SlotPorts = Readonly<
  Record<DeploySlot, Readonly<Record<DeployHttpServiceName, number>>>
>

/** Rewrites a release's HTTP services to listen on the given slot's loopback ports. */
export function releaseForSlot(
  release: DeployRelease,
  ports: Readonly<Record<DeployHttpServiceName, number>>
): DeployRelease {
  return {
    ...release,
    services: release.services.map((service) => {
      if (!service.http || (service.name !== "api" && service.name !== "app")) {
        return service
      }
      const port = ports[service.name]
      return {
        ...service,
        command: {
          ...service.command,
          args: replacePortArg(service.command.args, port),
        },
        http: {
          ...service.http,
          port,
        },
      }
    }),
  }
}

function replacePortArg(args: readonly string[], port: number): string[] {
  const next = [...args]
  const index = next.indexOf("--port")
  if (index !== -1 && index + 1 < next.length) {
    next[index + 1] = String(port)
  }
  return next
}

/** The supervisor's view of the release: absolute commands, full environments. */
export function renderProcessManifest(
  release: DeployRelease,
  layout: DeploymentLayout,
  options: { readonly projectDir?: string; readonly slot?: DeploySlot } = {}
): ProcessManifest {
  const projectDir = options.projectDir ?? layout.project
  const sixb = `${projectDir}/node_modules/.bin/sixb`
  return {
    version: 1,
    name: release.name,
    ...(options.slot ? { slot: options.slot } : {}),
    cwd: projectDir,
    runDir: layout.runDir,
    logDir: layout.logDir,
    releasePath: layout.releaseRecord,
    env: release.env,
    services: release.services.map((service) => ({
      name: service.name,
      kind: service.kind,
      processName: `${release.name}-${service.name}`,
      command: layout.bun,
      args:
        service.command.program === "sixb"
          ? [sixb, ...service.command.args]
          : [...service.command.args],
      env: serviceEnvWithDrain(service),
      instances: service.instances,
      killTimeoutMs: service.process.killTimeoutMs,
      restartDelayMs: service.process.restartDelayMs,
      ...(service.process.maxMemory ? { maxMemory: service.process.maxMemory } : {}),
    })),
  }
}

function serviceEnvWithDrain(service: DeployReleaseService): Record<string, string> {
  if (
    (service.name === "api" || service.name === "workers") &&
    service.env.SIXB_DRAIN_TIMEOUT_MS === undefined
  ) {
    return {
      SIXB_DRAIN_TIMEOUT_MS: String(RETIRING_DRAIN_TIMEOUT_MS),
      ...service.env,
    }
  }
  return { ...service.env }
}

/** Pins the server half of this package to the project's Bun and manifest. */
export function renderCtl(layout: DeploymentLayout): string {
  return [
    "#!/bin/sh",
    `# ${GENERATED}`,
    `exec ${shellQuote(layout.bun)} ${shellQuote(`${layout.project}/node_modules/.bin/sixb-deploy-ssh`)} "$@" --manifest ${shellQuote(layout.manifest)}`,
    "",
  ].join("\n")
}

/**
 * The deployment's `systemd --user` unit. Linger starts the user's systemd at boot, so the
 * unit comes back after a reboot without anyone logged in.
 */
export function renderUnit(release: DeployRelease, layout: DeploymentLayout): string {
  // Long enough for the supervisor to stop every process with its own kill timeout.
  const stopSeconds =
    Math.ceil(
      Math.max(...release.services.map((service) => service.process.killTimeoutMs)) / 1000
    ) + 10
  return [
    `# ${GENERATED}`,
    "[Unit]",
    `Description=Sixb deployment ${release.name}`,
    "",
    "[Service]",
    "Type=simple",
    `WorkingDirectory=${systemdValue(layout.project)}`,
    `Environment=${systemdValue(`PATH=${layout.bunDir}:/usr/local/bin:/usr/bin:/bin`)}`,
    `ExecStart=${systemdValue(layout.ctl)} supervise`,
    "Restart=always",
    "RestartSec=2",
    "KillSignal=SIGTERM",
    `TimeoutStopSec=${stopSeconds}`,
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n")
}

/** One site per HTTP service, forwarded to the active slot's loopback port. */
export function renderCaddySnippet(release: DeployRelease): string {
  const sites = release.services.flatMap((service) => {
    if (!service.http) return []
    const pages = service.name === "app"
    return [
      [
        `${service.http.domain} {`,
        ...(service.name === "api" ? compressJson() : []),
        `\treverse_proxy ${service.http.host}:${service.http.port} {`,
        "\t\tlb_try_duration 5s",
        "\t}",
        ...(pages ? updatePageOnProxyErrors() : []),
        "}",
      ].join("\n"),
    ]
  })
  return [`# ${GENERATED}`, "", sites.join("\n\n"), ""].join("\n")
}

/**
 * The API never compresses its responses, and an object query page is easily a megabyte of
 * JSON that compresses about twentyfold. Only complete JSON answers are encoded: the
 * WebSocket upgrade and anything else streamed through the API stay as they are, since an
 * encoder buffers what it writes. A 206 keeps its byte range of the stored file intact, and the
 * app's assets are already precompressed.
 */
function compressJson(): string[] {
  return [
    "\tencode {",
    "\t\tzstd",
    "\t\tgzip",
    "\t\tmatch {",
    "\t\t\tstatus 200",
    "\t\t\theader Content-Type application/json*",
    "\t\t}",
    "\t}",
  ]
}

/**
 * While the app is down — during an outage — a browser asking for a page gets the update page
 * instead of Caddy's bare error. Other requests keep the error.
 */
function updatePageOnProxyErrors(): string[] {
  return [
    "\thandle_errors 502 503 504 {",
    "\t\t@page {",
    "\t\t\tmethod GET",
    "\t\t\theader Accept *text/html*",
    "\t\t}",
    "\t\thandle @page {",
    '\t\t\theader Content-Type "text/html; charset=utf-8"',
    '\t\t\theader Cache-Control "no-store"',
    '\t\t\theader Retry-After "10"',
    "\t\t\trespond 503 {",
    "\t\t\t\tbody <<HTML",
    ...renderUpdatePage()
      .split("\n")
      .map((line) => `\t\t\t\t${line}`),
    "\t\t\t\tHTML",
    "\t\t\t}",
    "\t\t}",
    "\t\thandle {",
    '\t\t\trespond "Service temporarily unavailable" {err.status_code}',
    "\t\t}",
    "\t}",
  ]
}

function systemdValue(value: string): string {
  return value.replace(/%/g, "%%").replace(/\s/g, "\\x20")
}
